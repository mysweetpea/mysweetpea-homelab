#!/usr/bin/env python3
"""Daily feature-row rotation for the Moonfin home (LatestItemsExcludes).

Moonfin honours LatestItemsExcludes from GET /Users/Me (nginx sub_filter below
patches the aios server's hardcoded empty list). Excluded views are skipped
entirely by the client - libraries stay fully browsable, but no home row and no
Items/Latest fetch for them.

Stable core rows are always visible. Each day a new feature set rotates in:
1 anime sub-genre pair + 2 cross-genre combo pairs + 1 mood pair + 1 curated
pair + 1 wildcard pair (true crime / Korean / a decade), a mixed Netflix-style set.
Deterministic by date seed. The only artifact is the nginx snippet.

ponytail: regenerates + reloads nginx daily; nginx -t gates the reload, a bad
snippet self-restores from the backup.
"""
import json
import os
import random
import subprocess
import sys
import time
import urllib.request
from datetime import date

SNIPPET = "/etc/nginx/snippets/aiostreams-config-excludes.snippet.conf"
BACKUP = "/root/aiostreams-config-excludes.snippet.conf.bak-rotate"
CREDS = "/root/.aiostreams-warmer-creds.json"
STATE = "/root/.moonfin-rotate-state.json"
LOG = "/var/log/moonfin-rotate.log"

CORE = [  # streamer/popular rows retired from Home 2026-10-16 (browsable via the My Media hub)
    "Trending Movies", "Trending Shows",
    "New Releases Movies", "New Releases Shows",
    "Anime Movies", "Anime Shows",
]
ANIME_POOL = [
    ("Anime: Action & Adventure Movies", "Anime: Action & Adventure Shows"),
    ("Anime: Romance Movies", "Anime: Romance Shows"),
    ("Anime: Comedy Movies", "Anime: Comedy Shows"),
    ("Anime: Fantasy Movies", "Anime: Fantasy Shows"),
    ("Anime: Sci-Fi Movies", "Anime: Sci-Fi Shows"),
    ("Anime: Isekai Movies", "Anime: Isekai Shows"),
    ("Anime: Slice of Life Movies", "Anime: Slice of Life Shows"),
    ("Anime: Sports Movies", "Anime: Sports Shows"),
    ("Anime: Horror Movies", "Anime: Horror Shows"),
    ("Anime: Mecha Movies", "Anime: Mecha Shows"),
]
MOOD_POOL = [
    ("Feel-Good Movies", "Feel-Good Shows"),
    ("Dark & Gritty Movies", "Dark & Gritty Shows"),
    ("Mind-Bending Movies", "Mind-Bending Shows"),
    ("Cozy Movies", "Cozy Shows"),
    ("Epic Movies", "Epic Shows"),
]
CURATED_POOL = [
    ("Critically Acclaimed Movies", "Critically Acclaimed Shows"),
    ("Hidden Gems Movies", "Hidden Gems Shows"),
    ("Best of All Time Movies", "Best of All Time Shows"),
    ("Cult Classics Movies", "Cult Classics Shows"),
]
COMBO_POOL = [
    ("Action Comedy Movies", "Action Comedy Shows"),
    ("Crime Drama Movies", "Crime Drama Shows"),
    ("Dark Comedy Movies", "Dark Comedy Shows"),
    ("Family Adventure Movies", "Family Adventure Shows"),
    ("Fantasy Adventure Movies", "Fantasy Adventure Shows"),
    ("Horror Thriller Movies", "Horror Thriller Shows"),
    ("Psychological Thriller Movies", "Psychological Thriller Shows"),
    ("Romantic Comedy Movies", "Romantic Comedy Shows"),
    ("Sci-Fi Thriller Movies", "Sci-Fi Thriller Shows"),
    ("Superhero Movies", "Superhero Shows"),
]
WILDCARD_POOL = [
    ("True Crime Movies", "True Crime Shows"),
    ("Korean Movies", "K-Dramas"),
    ("80s Movies", "80s Shows"),
    ("90s Movies", "90s Shows"),
    ("2000s Movies", "2000s Shows"),
]

CREDS_BASE = ""


def log(msg):
    line = time.strftime("%Y-%m-%d %H:%M:%S ") + msg
    print(line, flush=True)
    try:
        open(LOG, "a").write(line + "\n")
    except OSError:
        pass


def pick(pool, k, seed):
    pool = sorted(pool)
    random.Random(seed).shuffle(pool)
    return pool[:k]


def features_for(seed):
    return (pick(ANIME_POOL, 1, seed * 11 + 1) +
            pick(COMBO_POOL, 2, seed * 11 + 2) +
            pick(MOOD_POOL, 1, seed * 11 + 3) +
            pick(CURATED_POOL, 1, seed * 11 + 4) +
            pick(WILDCARD_POOL, 1, seed * 11 + 5))


def snippet_text(excluded_ids):
    ids = ", ".join('"%s"' % i for i in excluded_ids)
    return (
        "# Server-side \"LatestItemsExcludes\" injection for the AIOStreams media server.\n"
        "# GENERATED by /root/moonfin-rotate.py - edit the script, not this file\n"
        "# (the next daily run overwrites it). Moonfin fetches one Items/Latest per\n"
        "# visible catalog view; excluded views are skipped entirely, fetch included.\n"
        "# Stable core rows + today's rotated feature rows stay visible.\n"
        "sub_filter '\"LatestItemsExcludes\":[]' '\"LatestItemsExcludes\":[%s]';\n"
        "sub_filter_once on;\n"
        "sub_filter_types *;\n" % ids
    )


def fetch(path, token=None, data=None):
    url = CREDS_BASE + path
    headers = {}
    if token:
        headers["Authorization"] = 'MediaBrowser Token="%s"' % token
    if data is not None:
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, headers=headers)
    return json.load(urllib.request.urlopen(req, timeout=20))


def main():
    global CREDS_BASE
    dry = "--dry-run" in sys.argv
    seed = int(os.environ.get("ROTATE_SEED") or date.today().strftime("%Y%m%d"))
    creds = json.load(open(CREDS))
    CREDS_BASE = creds["base"].rstrip("/")
    body = json.dumps({"Username": creds["uuid"], "Pw": creds["password"]}).encode()
    tok = fetch("/Users/AuthenticateByName", data=body)["AccessToken"]
    views = fetch("/UserViews", token=tok).get("Items", [])
    name2id = {v.get("Name"): v.get("Id") for v in views if v.get("Name")}
    feats = features_for(seed)
    visible = set(CORE)
    for pair in feats:
        visible.update(pair)
    missing = sorted(n for n in visible if n not in name2id)
    if missing:
        log("WARN: visible names absent from UserViews: %s" % ", ".join(missing))
    excluded = [name2id[v.get("Name")] for v in views
                if v.get("Name") not in visible and v.get("Name") in name2id]
    text = snippet_text(excluded)
    state = {"seed": seed, "features": [list(p) for p in feats],
             "visible": len(visible), "excluded": len(excluded), "ts": time.time(),
             "visible_names": sorted(visible)}
    log("seed=%s features=%s excluded=%d/%d" % (seed, [p[0] for p in feats], len(excluded), len(views)))
    if dry:
        print(text)
        return 0
    try:
        open(BACKUP, "w").write(open(SNIPPET).read())
    except OSError:
        pass
    open(SNIPPET, "w").write(text)
    t = subprocess.run(["nginx", "-t"], capture_output=True, text=True)
    if t.returncode != 0:
        log("nginx -t FAILED, restoring previous snippet: %s" % t.stderr.strip()[-300:])
        try:
            open(SNIPPET, "w").write(open(BACKUP).read())
        except OSError:
            pass
        subprocess.run(["systemctl", "reload", "nginx"])
        return 1
    subprocess.run(["systemctl", "reload", "nginx"], check=True)
    json.dump(state, open(STATE, "w"), indent=1)
    time.sleep(5)  # a draining nginx worker can serve the pre-reload response for a few seconds
    try:
        me = fetch("/Users/Me", token=tok)
        got = (me.get("Configuration") or {}).get("LatestItemsExcludes") or []
        ok = len(got) == len(excluded)
        log("verify: /Users/Me LatestItemsExcludes=%d expected=%d %s" % (len(got), len(excluded), "OK" if ok else "MISMATCH"))
    except Exception as e:
        log("verify failed: %s" % e)
    try:
        subprocess.run(["flock", "-n", "/tmp/aiostreams-warmer.lock", "/usr/bin/python3",
                        "/root/aiostreams-warmer.py"], timeout=300, capture_output=True)
    except Exception as e:
        log("warmer trigger skipped: %s" % e)
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        f1, f2 = features_for(20261016), features_for(20261016)
        assert f1 == f2 and len(f1) == 6, "features must be deterministic, 6 pairs"
        assert len(set(f1)) == 6, "no duplicate pairs in a day"
        text = snippet_text(["abc", "def"])
        assert '"LatestItemsExcludes":["abc", "def"]' in text
        assert len(CORE) == 6 and len(ANIME_POOL) == 10 and len(COMBO_POOL) == 10
        assert len(MOOD_POOL) == 5 and len(CURATED_POOL) == 4 and len(WILDCARD_POOL) == 5
        print("selftest ok")
        sys.exit(0)
    sys.exit(main())
